package model.enums;

/**
 * Enum representing the cardinal directions.
 * This enum is used to specify the four primary directions:
 * North, South, East, and West.
 */
public enum Direction {

  /** Represents the top. */
  NORTH,

  /** Represents the bottom. */
  SOUTH,

  /** Represents the right. */
  EAST,

  /** Represents the left. */
  WEST
}